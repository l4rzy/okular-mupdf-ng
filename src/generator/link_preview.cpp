class PreviewScrollArea final : public QScrollArea {
public:
    explicit PreviewScrollArea(QWidget* parent)
        : QScrollArea(parent)
        , m_scroller(QScroller::scroller(viewport()))
    {
        viewport()->setCursor(Qt::OpenHandCursor);
        auto properties = m_scroller->scrollerProperties();
        const auto noOvershoot = QVariant::fromValue(QScrollerProperties::OvershootAlwaysOff);
        properties.setScrollMetric(QScrollerProperties::HorizontalOvershootPolicy, noOvershoot);
        properties.setScrollMetric(QScrollerProperties::VerticalOvershootPolicy, noOvershoot);
        m_scroller->setScrollerProperties(properties);
    }

    bool isDragging() const { return m_pressed; }

    void stopScrolling()
    {
        m_pressed = false;
        m_scroller->stop();
        viewport()->setCursor(Qt::OpenHandCursor);
    }

protected:
    bool viewportEvent(QEvent* event) override
    {
        // A normal release can also relinquish the implicit mouse grab; only
        // an interrupted drag should stop momentum here.
        if (event->type() == QEvent::UngrabMouse && m_pressed)
            stopScrolling();
        return QScrollArea::viewportEvent(event);
    }

    void mousePressEvent(QMouseEvent* event) override
    {
        stopScrolling();
        if (event->button() != Qt::LeftButton) {
            QScrollArea::mousePressEvent(event);
            return;
        }
        m_pressed = true;
        viewport()->setCursor(Qt::ClosedHandCursor);
        handleInput(QScroller::InputPress, event);
        event->accept();
    }

    void mouseMoveEvent(QMouseEvent* event) override
    {
        if (m_pressed && !(event->buttons() & Qt::LeftButton))
            stopScrolling();
        if (!m_pressed) {
            QScrollArea::mouseMoveEvent(event);
            return;
        }
        handleInput(QScroller::InputMove, event);
        event->accept();
    }

    void mouseReleaseEvent(QMouseEvent* event) override
    {
        if (event->button() != Qt::LeftButton || !m_pressed) {
            QScrollArea::mouseReleaseEvent(event);
            return;
        }
        m_pressed = false;
        viewport()->setCursor(Qt::OpenHandCursor);
        handleInput(QScroller::InputRelease, event);
        event->accept();
    }

    void wheelEvent(QWheelEvent* event) override
    {
        stopScrolling();
        QScrollArea::wheelEvent(event);
    }

    void hideEvent(QHideEvent* event) override
    {
        stopScrolling();
        QScrollArea::hideEvent(event);
    }

private:
    void handleInput(QScroller::Input input, QMouseEvent* event)
    {
        // Keep mouse handling local to the preview; QScrollArea applies the
        // scroll events generated by Qt using these viewport coordinates.
        m_scroller->handleInput(input, event->position(), static_cast<qint64>(event->timestamp()));
    }

    QScroller* m_scroller;
    bool m_pressed = false;
};

class LinkPreviewWindow final : public QFrame {
public:
    LinkPreviewWindow(QWidget* parent, std::function<void()> onScroll)
        : QFrame(parent, Qt::ToolTip | Qt::FramelessWindowHint | Qt::WindowDoesNotAcceptFocus)
    {
        setObjectName(QStringLiteral("mupdfLinkPreview"));
        setWindowTitle(i18n("Link preview"));
        setAttribute(Qt::WA_ShowWithoutActivating);
        // Tool windows otherwise use the application palette instead of the
        // owning Okular window's color scheme. Inherit it, including live changes.
        setAttribute(Qt::WA_WindowPropagation);
        // Only pixels outside the rounded outline are transparent.
        setAttribute(Qt::WA_TranslucentBackground);
        auto* layout = new QVBoxLayout(this);
        layout->setContentsMargins(6, 6, 6, 6);
        m_header = new QWidget(this);
        auto* headerLayout = new QHBoxLayout(m_header);
        headerLayout->setContentsMargins(0, 0, 0, 0);
        m_status = new QLabel(m_header);
        m_status->setWordWrap(true);
        m_status->setForegroundRole(QPalette::WindowText);
        headerLayout->addWidget(m_status, 1, Qt::AlignTop);
        auto* hint = new QLabel(i18n("Press Esc to cancel"), m_header);
        hint->setWordWrap(true);
        hint->setAlignment(Qt::AlignRight | Qt::AlignTop);
        hint->setForegroundRole(QPalette::WindowText);
        headerLayout->addWidget(hint, 1, Qt::AlignTop);
        layout->addWidget(m_header);
        m_scroll = new PreviewScrollArea(this);
        // Let the viewport shrink below its size hint when the header wraps.
        m_scroll->setMinimumHeight(1);
        m_scroll->setFrameShape(QFrame::NoFrame);
        m_scroll->setVerticalScrollBarPolicy(Qt::ScrollBarAlwaysOff);
        m_scroll->setHorizontalScrollBarPolicy(Qt::ScrollBarAlwaysOff);
        m_scroll->viewport()->setBackgroundRole(QPalette::Window);
        layout->addWidget(m_scroll);
        // Defer viewport notifications until page placeholders and the initial
        // destination position have all been installed.
        const auto requestPages = [onScroll = std::move(onScroll)] {
            onScroll();
        };
        connect(m_scroll->verticalScrollBar(), &QScrollBar::valueChanged, this, requestPages, Qt::QueuedConnection);
        connect(m_scroll->verticalScrollBar(), &QScrollBar::rangeChanged, this, requestPages, Qt::QueuedConnection);
    }

    bool isDragging() const { return m_scroll->isDragging(); }

    void prepare(int page, LinkPreviewSize size, bool loading, const QRect& available, QPoint anchor)
    {
        m_scroll->stopScrolling();
        m_status->setText(loading ? i18n("Page %1 — Loading preview…", static_cast<qint64>(page) + 1)
                                  : i18n("Page %1", static_cast<qint64>(page) + 1));
        m_scroll->setFixedWidth(size.render.width());
        m_header->setFixedWidth(size.render.width());
        ensurePolished();
        // Apply the new minimum size before resize() can clamp to the old width.
        layout()->activate();
        resize(std::min(available.width(), sizeHint().width()), std::min(available.height(), size.visibleHeight + 48));
        const int x = anchor.x() + 12 + width() <= available.right() + 1 ? anchor.x() + 12 : anchor.x() - width() - 12;
        const int y =
            anchor.y() + 20 + height() <= available.bottom() + 1 ? anchor.y() + 20 : anchor.y() - height() - 12;
        move(std::clamp(x, available.left(), std::max(available.left(), available.right() - width() + 1)),
             std::clamp(y, available.top(), std::max(available.top(), available.bottom() - height() + 1)));
    }

    void showUnavailable() { m_status->setText(i18n("Preview unavailable")); }

    void clearPages(QSize size)
    {
        m_scroll->stopScrolling();
        m_labels.clear();
        auto* content = new QWidget;
        content->setBackgroundRole(QPalette::Dark);
        content->setFixedSize(size);
        m_scroll->setWidget(content);
    }

    void addPage(int number, const QRect& rect, bool target)
    {
        auto* label = new QLabel(i18n("Loading preview…"), m_scroll->widget());
        label->setGeometry(rect);
        label->setAlignment(Qt::AlignCenter);
        label->setForegroundRole(QPalette::WindowText);
        label->setBackgroundRole(QPalette::Window);
        label->setAutoFillBackground(true);
        label->setObjectName(target ? QStringLiteral("previewImage") : QStringLiteral("previewPage"));
        label->setProperty("pageNumber", number);
        label->show();
        m_labels.push_back(label);
    }

    void setPage(std::size_t index, const QImage& image, bool target)
    {
        auto* label = m_labels[index];
        if (image.isNull())
            label->setText(i18n("Preview unavailable"));
        else
            label->setPixmap(QPixmap::fromImage(image));
        if (target) {
            if (image.isNull())
                showUnavailable();
            else
                m_status->setText(i18n("Page %1", label->property("pageNumber").toLongLong() + 1));
        }
        // Keep geometry and scroller state intact while a neighbor arrives.
    }

    void scrollToTarget(const QRect& target, double targetY)
    {
        m_scroll->verticalScrollBar()->setValue(
            std::clamp(target.top() + static_cast<int>(targetY * target.height()) - 24,
                       0,
                       m_scroll->verticalScrollBar()->maximum()));
    }

    bool isPageVisible(const QRect& page) const
    {
        return page.intersects(
            QRect(QPoint(m_scroll->horizontalScrollBar()->value(), m_scroll->verticalScrollBar()->value()),
                  m_scroll->viewport()->size()));
    }

protected:
    void paintEvent(QPaintEvent*) override
    {
        QPainter painter(this);
        painter.setRenderHint(QPainter::Antialiasing);
        const auto opaqueColor = [this](QPalette::ColorRole role) {
            QColor color = palette().color(role);
            color.setAlpha(255);
            return color;
        };
        painter.setPen(QPen(opaqueColor(QPalette::Mid), 1));
        painter.setBrush(opaqueColor(QPalette::Window));
        painter.drawRoundedRect(QRectF(rect()).adjusted(0.5, 0.5, -0.5, -0.5), 6, 6);
    }

private:
    QWidget* m_header;
    QLabel* m_status;
    PreviewScrollArea* m_scroll;
    std::vector<QLabel*> m_labels;
};

LinkPreview::LinkPreview(Renderer render, PageInfo pageInfo)
    : m_render(std::move(render))
    , m_pageInfo(std::move(pageInfo))
{
    m_pool.setMaxThreadCount(1);
    m_closeTimer.setSingleShot(true);
    m_closeTimer.setInterval(350);
    connect(&m_closeTimer, &QTimer::timeout, this, [this] {
        if (!isHovered())
            dismiss();
    });
}

LinkPreview::~LinkPreview()
{
    reset();
}

LinkPreviewPage LinkPreview::describePage(const Okular::Page* page)
{
    if (!page)
        return { };
    const bool sideways = page->rotation() == Okular::Rotation90 || page->rotation() == Okular::Rotation270;
    return { sideways ? QSizeF(page->height(), page->width()) : QSizeF(page->width(), page->height()) };
}

void LinkPreview::dismiss()
{
    m_closeTimer.stop();
    qApp->removeEventFilter(this);
    if (m_cancelled)
        m_cancelled->store(true);
    if (m_window)
        m_window->hide();
    m_source.clear();
}

void LinkPreview::reset()
{
    clearPreview();
    for (const auto& scales : std::as_const(m_renderScales))
        disconnect(scales.destroyed);
    m_renderScales.clear();
}

void LinkPreview::clearPreview()
{
    dismiss();
    ++m_generation;
    m_pool.waitForDone();
    m_cancelled.reset();
    m_cache.clear();
    m_pages.clear();
    m_key.clear();
    delete m_window.data();
}

void LinkPreview::setMode(LinkPreviewMode mode)
{
    if (m_mode == mode)
        return;
    clearPreview();
    m_mode = mode;
}

void LinkPreview::observeRender(QWidget* view, int page, QSize renderSize)
{
    if (!view || renderSize.isEmpty())
        return;
    const double pageWidth = m_pageInfo(page).size.width();
    if (!std::isfinite(pageWidth) || pageWidth <= 0)
        return;
    const double scale = renderSize.width() / view->devicePixelRatioF() / pageWidth;
    if (!std::isfinite(scale) || scale <= 0)
        return;
    auto entry = m_renderScales.find(view);
    if (entry == m_renderScales.end()) {
        entry = m_renderScales.insert(view, ViewRenderScales { });
        entry->destroyed = connect(view, &QObject::destroyed, this, [this, view] { m_renderScales.remove(view); });
    }
    entry->pages.insert(page, scale);
    entry->latest = scale;
}

bool LinkPreview::showPreview(const Model::Viewport& destination, int sourcePage)
{
    if (m_mode == LinkPreviewMode::Off || destination.page < 0)
        return false;
    auto* source = QApplication::widgetAt(QCursor::pos());
    if (!source)
        return false;
    if (m_window && (source == m_window.data() || m_window->isAncestorOf(source)))
        return true; // A delayed source tooltip must not replace the open preview.
    auto* screen = QGuiApplication::screenAt(QCursor::pos());
    if (!screen)
        screen = source->screen();
    if (!screen)
        return false;
    // Presets stay stable across zoom, window resizing, mode changes and resets.
    if (m_sessionScreen.isEmpty())
        m_sessionScreen = screen->geometry().size();
    const QRect available = screen->availableGeometry();
    double previewScale = 0;
    // A cached source page may have a different scale from the last rendered page.
    for (auto* widget = source; widget; widget = widget->parentWidget()) {
        const auto entry = m_renderScales.constFind(widget);
        if (entry == m_renderScales.cend())
            continue;
        const double scale = sourcePage < 0 ? entry->latest : entry->pages.value(sourcePage);
        if (scale > 0) {
            // Cap the preview to 70% of the current logical page render.
            previewScale = scale * 0.70;
            break;
        }
    }
    const auto sizeForPage = [&](int page, double scale) {
        // QScreen geometry is in logical pixels: half of it is also half the
        // native pixel resolution after accounting for display scaling.
        const QSize bounds = m_mode == LinkPreviewMode::AdaptiveSize ? screen->geometry().size() : available.size();
        return sizeLinkPreview(m_mode, source->window()->size(), bounds, m_pageInfo(page), scale, m_sessionScreen);
    };
    LinkPreviewSize previewSize = sizeForPage(destination.page, previewScale);
    if (previewSize.render.isEmpty())
        return false;
    double commonScale = previewSize.scale;
    std::vector<RenderPage> pages;
    QString key = QString::number(destination.page);
    for (int offset : { -1, 0, 1 }) {
        if ((offset < 0 && destination.page == 0)
            || (offset > 0 && destination.page == std::numeric_limits<int>::max()))
            continue;
        const int page = destination.page + offset;
        const auto size = offset == 0 ? previewSize : sizeForPage(page, previewSize.scale);
        if (size.render.isEmpty())
            continue;
        commonScale = std::min(commonScale, size.scale);
        pages.push_back({ page, QRect(QPoint(), size.render) });
    }
    if (m_mode == LinkPreviewMode::AdaptiveSize) {
        // Fit all three pages at one scale, including wide/tall neighbors.
        previewSize = sizeForPage(destination.page, commonScale);
        for (auto& page : pages)
            page.rect.setSize(sizeForPage(page.number, commonScale).render);
    }
    // Neighbors can have different page dimensions. Fit the widest page.
    for (const auto& page : pages) {
        previewSize.render.setWidth(std::max(previewSize.render.width(), page.rect.width()));
        key += QStringLiteral(":%1:%2:%3").arg(page.number).arg(page.rect.width()).arg(page.rect.height());
    }
    if (m_cancelled && (key != m_key || m_cancelled->load())) {
        dismiss();
        return false; // Keep at most one render in flight; never queue hover jobs.
    }

    const bool newLayout =
        key != m_key || !m_window || !m_window->isVisible() || m_window->parentWidget() != source->window();
    m_source = source;
    m_anchor = QCursor::pos();
    m_key = key;
    const double targetY =
        (destination.coordinateMask & Model::Viewport::CoordinateY) != 0 && std::isfinite(destination.normalizedY)
        ? std::clamp(destination.normalizedY, 0.0, 1.0)
        : 0.0;
    if (m_window && m_window->parentWidget() != source->window())
        delete m_window.data();
    if (!m_window)
        m_window = new LinkPreviewWindow(source->window(), [this] { renderVisiblePages(); });
    if (newLayout) {
        constexpr int PageGap = 8;
        m_pages = std::move(pages);
        int top = 0;
        for (std::size_t i = 0; i < m_pages.size(); ++i) {
            auto& page = m_pages[i];
            page.rect.moveTopLeft(QPoint((previewSize.render.width() - page.rect.width()) / 2, top));
            top += page.rect.height() + PageGap;
            if (page.number == destination.page)
                m_targetIndex = i;
        }
        m_window->clearPages(QSize(previewSize.render.width(), top - PageGap));
        for (std::size_t i = 0; i < m_pages.size(); ++i)
            m_window->addPage(m_pages[i].number, m_pages[i].rect, i == m_targetIndex);
    }
    m_window->setScreen(screen);
    m_window->prepare(
        destination.page, previewSize, m_pages[m_targetIndex].state == PageState::Pending, available, m_anchor);
    if (m_pages[m_targetIndex].state == PageState::Failed)
        m_window->showUnavailable();
    m_closeTimer.stop();
    QToolTip::hideText();
    qApp->installEventFilter(this);
    m_window->show();
    m_window->scrollToTarget(m_pages[m_targetIndex].rect, targetY);
    renderVisiblePages();
    return true;
}

QString LinkPreview::pageKey(const RenderPage& page)
{
    return QStringLiteral("%1:%2:%3").arg(page.number).arg(page.rect.width()).arg(page.rect.height());
}

void LinkPreview::renderVisiblePages()
{
    if (!m_window || !m_window->isVisible() || m_pages.empty() || m_cancelled)
        return;
    if (m_pages[m_targetIndex].state == PageState::Failed)
        return;
    const auto load = [this](std::size_t index) {
        auto& page = m_pages[index];
        if (const auto* cached = m_cache.object(pageKey(page))) {
            page.state = PageState::Ready;
            m_window->setPage(index, *cached, index == m_targetIndex);
        } else {
            startRender(index);
        }
    };
    // Show the destination before spending worker time on visible neighbors.
    if (m_pages[m_targetIndex].state == PageState::Pending)
        load(m_targetIndex);
    for (std::size_t i = 0; i < m_pages.size() && !m_cancelled; ++i)
        if (m_pages[i].state == PageState::Pending && m_window->isPageVisible(m_pages[i].rect))
            load(i);
}

void LinkPreview::startRender(std::size_t index)
{
    m_cancelled = std::make_shared<std::atomic_bool>(false);
    const auto cancelled = m_cancelled;
    const auto generation = m_generation;
    const auto render = m_render;
    const auto page = m_pages[index];
    const QString key = pageKey(page);
    m_pool.start([this, render, cancelled, generation, key, page, index] {
        QImage image;
        if (!cancelled->load())
            image = render(page.number, page.rect.size(), [cancelled] { return cancelled->load(); });
        // Worker images lease shared frame slots. Keep owned pixels so cached
        // and displayed pages cannot exhaust the worker's frame pool.
        image = !cancelled->load() && image.size() == page.rect.size() ? image.copy() : QImage { };
        QMetaObject::invokeMethod(this, [this, cancelled, generation, key, index, image = std::move(image)] {
            if (generation != m_generation)
                return;
            m_cancelled.reset();
            if (cancelled->load())
                return;
            m_pages[index].state = image.isNull() ? PageState::Failed : PageState::Ready;
            if (!image.isNull())
                m_cache.insert(key, new QImage(image), static_cast<int>((image.sizeInBytes() + 1023) / 1024));
            if (m_window && m_window->isVisible()) {
                m_window->setPage(index, image, index == m_targetIndex);
                renderVisiblePages();
            }
        });
    });
}

bool LinkPreview::isHovered() const
{
    if (!m_window || !m_window->isVisible() || !m_source || !m_source->isVisible())
        return false;
    if (m_window->isDragging() && (QApplication::mouseButtons() & Qt::LeftButton))
        return true;
    const QPoint position = QCursor::pos();
    return m_window->frameGeometry().contains(position)
        || (QApplication::widgetAt(position) == m_source
            && QRect(m_anchor - QPoint(4, 4), QSize(9, 9)).contains(position));
}

bool LinkPreview::eventFilter(QObject* watched, QEvent* event)
{
    if (!m_window || !m_window->isVisible())
        return false;
    const auto* widget = qobject_cast<QWidget*>(watched);
    const bool inPreview = watched == m_window->windowHandle()
        || (widget && (widget == m_window.data() || m_window->isAncestorOf(widget)));
    switch (event->type()) {
    case QEvent::MouseButtonRelease:
    case QEvent::UngrabMouse:
        // Input reaches this filter before the scroll area clears its drag
        // state. Check hover after that transition, at the grace deadline.
        m_closeTimer.start();
        break;
    case QEvent::MouseMove:
    case QEvent::Enter:
    case QEvent::Leave:
        if (isHovered())
            m_closeTimer.stop();
        else if (!m_closeTimer.isActive())
            m_closeTimer.start();
        break;
    case QEvent::KeyPress:
        if (static_cast<QKeyEvent*>(event)->key() == Qt::Key_Escape) {
            dismiss();
            return true;
        }
        [[fallthrough]];
    case QEvent::MouseButtonPress:
    case QEvent::Wheel:
        if (!inPreview)
            dismiss();
        break;
    case QEvent::Hide:
    case QEvent::WindowDeactivate:
        if (m_source && (watched == m_source || watched == m_source->window()))
            dismiss();
        break;
    default:
        break;
    }
    return false;
}

